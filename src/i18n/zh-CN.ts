function localizeCategory(category: Category): Category {
  const translation = categoryTranslations[category.id];
  return translation ? { ...category, ...translation } : category;
}

function localizeTool(tool: Tool): Tool {
  return {
    ...tool,
    description: toolDescriptionsZh[tool.id] ?? tool.description,
    tagsZh: tool.tags.map((tag) => tagTranslations[tag] ?? tag),
  };
}

export function localizeToolsData(data: ToolsData): ToolsData {
  return {
    categories: data.categories.map(localizeCategory),
    tools: data.tools.map(localizeTool),
  };
}
